// Exports the TLA+ sources bundled in the TypeScript implementation (bundled.ts) into rust/lib/*.tla
// and regenerates src/bundled.rs. usage: node scripts/export-lib.mjs /path/to/ts/src/bundled.ts
import fs from 'node:fs';
import path from 'node:path';
const src = fs.readFileSync(process.argv[2], 'utf8');
const obj = (0, eval)('(' + src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1) + ')');
const here = path.resolve(import.meta.dirname, '..');
let rs = '// Generated by scripts/export-lib.mjs - do not edit.\npub static BUNDLED: &[(&str, &str)] = &[\n';
for (const [name, text] of Object.entries(obj)) {
  fs.writeFileSync(path.join(here, 'lib', name + '.tla'), text);
  rs += `    ("${name}", include_str!("../lib/${name}.tla")),\n`;
}
rs += '];\n';
fs.writeFileSync(path.join(here, 'src', 'bundled.rs'), rs);
