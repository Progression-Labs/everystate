// Generates src/bundled.ts from the TLA+ community modules (MIT) and TLC's standard TLA+ modules.
import fs from 'node:fs';
import path from 'node:path';
const dirs = process.argv.slice(2);
const skip = new Set(['Naturals', 'Integers', 'Reals', 'Sequences', 'FiniteSets', 'TLC', 'TLCExt', 'Bags', 'Randomization']);
const out = {};
for (const d of dirs) for (const f of fs.readdirSync(d).sort()) {
  if (!f.endsWith('.tla')) continue;
  const name = f.slice(0, -4);
  if (skip.has(name) || name.startsWith('_') || out[name]) continue;
  out[name] = fs.readFileSync(path.join(d, f), 'utf8');
}
let s = '// GENERATED by scripts/bundle.mjs - TLA+ sources of bundled library modules. Do not edit.\n';
s += 'export const BUNDLED: Record<string, string> = ' + JSON.stringify(out, null, 0)+ ";\n";
fs.writeFileSync('src/bundled.ts', s);
console.log(Object.keys(out).join(' '));
