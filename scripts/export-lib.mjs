// Exports the TLA+ sources bundled in the TypeScript implementation (bundled.ts) into lib/*.tla
// and regenerates src/bundled.rs. usage: node scripts/export-lib.mjs /path/to/ts/src/bundled.ts
import fs from 'node:fs';
import path from 'node:path';
const here = path.resolve(import.meta.dirname, '..');
// Without an argument: regenerate src/bundled.rs from the lib/*.tla files already present.
let obj;
if (process.argv[2]) {
  const src = fs.readFileSync(process.argv[2], 'utf8');
  obj = (0, eval)('(' + src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1) + ')');
} else {
  obj = Object.fromEntries(fs.readdirSync(path.join(here, 'lib')).filter(f => f.endsWith('.tla')).sort().map(f => [f.slice(0, -4), fs.readFileSync(path.join(here, 'lib', f), 'utf8')]));
}
let rs = '// Generated by scripts/export-lib.mjs - do not edit.\npub static BUNDLED: &[(&str, &str)] = &[\n';
for (const [name, text] of Object.entries(obj)) {
  fs.writeFileSync(path.join(here, 'lib', name + '.tla'), text);
  rs += `    ("${name}", include_str!("../lib/${name}.tla")),\n`;
}
rs += '];\n';
fs.writeFileSync(path.join(here, 'src', 'bundled.rs'), rs);
